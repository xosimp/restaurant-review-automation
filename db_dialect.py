_NUMERIC_LOADER = None


def _numeric_loader():
    """psycopg's loader for `numeric` answering as SQLite does: SUM() of
    integers an int, anything with a fraction a float. Postgres's sum(bigint)
    and avg() are numeric, which psycopg hands back as Decimal — and
    Decimal * float raises TypeError in the app's arithmetic (blind re-audit
    10/11/26, SCALE-9)."""
    global _NUMERIC_LOADER
    if _NUMERIC_LOADER is None:
        from decimal import Decimal
        from psycopg.adapt import Loader

        class SqliteNumericLoader(Loader):
            def load(self, data):
                if isinstance(data, memoryview):
                    data = bytes(data)
                d = Decimal(data.decode() if isinstance(data, (bytes, bytearray)) else data)
                if d.is_nan():
                    return float("nan")
                return int(d) if d == d.to_integral_value() and "." not in str(data) else float(d)
        _NUMERIC_LOADER = SqliteNumericLoader
    return _NUMERIC_LOADER


def _driver_connect(url):
    import psycopg
    # UTC, as SQLite's datetime('now') is: a stamp with no offset is read
    # as UTC (cavnar_ts), and now() / CURRENT_DATE agree with the app.
    # Timeouts (scale audit 10/19/26 DB-06): SQLite gave up on a lock after
    # its 30 s busy_timeout; Postgres would wait forever, and one stuck
    # transaction holding WRITE_LOCK_KEY stopped every BEGIN IMMEDIATE in
    # every process. 0 turns one off.
    opts = ["-c timezone=UTC",
            f"-c lock_timeout={_env_int(os.getenv('PG_LOCK_TIMEOUT_MS'), 30000)}",
            f"-c statement_timeout={_env_int(os.getenv('PG_STATEMENT_TIMEOUT_MS'), 300000)}",
            f"-c idle_in_transaction_session_timeout={_env_int(os.getenv('PG_IDLE_TX_TIMEOUT_MS'), 300000)}"]
    # PG_WORK_MEM (e.g. 16MB): the memory one sort or hash of this app's
    # sessions may take before it spills to disk — the server's default is
    # 4 MB (blind re-audit 10/20/26 R2-10). Unset: the server's own value.
    # shared_buffers / effective_cache_size are the server's, set on Railway
    # (docs/ops/POSTGRES_CUTOVER.md).
    wm = (os.getenv("PG_WORK_MEM") or "").strip()
    if re.fullmatch(r"\d{1,7}(kB|MB|GB)?", wm):
        opts.append(f"-c work_mem={wm}")
    # PG_CONNECT_TIMEOUT_S (5): a server that does not answer a connect is
    # given up on this soon (it was 10 s, and every request thread waited
    # it out in turn while the database restarted - DB-22).
    raw = psycopg.connect(url, autocommit=False, connect_timeout=max(2, _env_int(os.getenv("PG_CONNECT_TIMEOUT_S"), 5)),
                          options=" ".join(opts))
    # Behind PgBouncer in transaction mode (before 1.21) a server-side
    # prepared statement may not exist on the next backend (DB-07):
    # PG_PREPARE_THRESHOLD=off never prepares.
    if (os.getenv("PG_PREPARE_THRESHOLD") or "").strip().lower() in ("off", "none", "0"):
        raw.prepare_threshold = None
    raw.adapters.register_loader("numeric", _numeric_loader())
    return raw


def _env_int(value, default):
    try:
        return max(0, int(value or default))
    except ValueError:
        return default


def _env_float(value, default):
    try:
        return max(0.0, float(value if value not in (None, "") else default))
    except ValueError:
        return default


def _alive(raw, ping=False) -> bool:
    """Whether an idle connection can be handed out: open, not broken, its
    socket's status OK — and, with `ping`, answering a round trip (DB-22)."""
    try:
        if getattr(raw, "closed", False) or getattr(raw, "broken", False):
            return False
        pgconn = getattr(raw, "pgconn", None)
        if pgconn is not None:
            from psycopg import pq
            if pgconn.status != pq.ConnStatus.OK:
                return False
        if ping:
            try:
                raw.execute("SELECT 1", prepare=False)
            except TypeError:               # a DB-API driver without `prepare`
                raw.cursor().execute("SELECT 1")
            raw.rollback()
        return True
    except Exception:
        return False


class _Pool:
    """One process's connections to one Postgres URL (SCALE-11). The app
    opens a connection per unit of work (get_conn … close), often one
    inside another on the same thread; per-thread idle lists with no cap
    grew with every thread the process runs (request threads, the
    scheduler, the queue's and the AI pools: 60-150 a process against
    Railway's max_connections of 100). Here:

      PG_POOL_MAX (20)       connections a process may have checked out by
                             threads that held none — the cap that matters;
      PG_POOL_OVERFLOW (20)  more, only for a thread that already holds one
                             (a nested get_conn: waiting there on threads
                             that wait on it would deadlock);
      PG_POOL_IDLE (5)       idle connections kept for reuse;
      PG_POOL_MAX_LIFETIME (1800 s) a connection's age before it is retired
                             at its next return; PG_POOL_IDLE_SECONDS (300)
                             an idle one's;
      PG_POOL_TIMEOUT (30 s) how long a checkout waits for a free one
                             before it fails, said.

    So a process holds at most PG_POOL_MAX + PG_POOL_OVERFLOW connections
    (40), and the web process plus worker.py at most 80 — under the 100
    Railway allows, with room for a deploy's overlap at the defaults' idle
    level. Behind PgBouncer (transaction mode) the same caps apply per
    process; the advisory locks are transaction-scoped, which it keeps."""

    def __init__(self, url):
        self.url = url
        self.cond = threading.Condition()
        self.idle = []                    # [(raw, born, idle_since)]
        self.base = 0                     # checked out by a thread holding none
        self.overflow = 0                 # checked out by a thread already holding one
        self.opened = 0                   # live raw connections (out + idle)
        self.down_until = 0.0             # the connect breaker (DB-22): monotonic
        self.down_error = ""

    def limits(self):
        # Read each checkout (cheap), so a changed limit needs no restart.
        return (_env_int(os.getenv("PG_POOL_MAX"), 20), _env_int(os.getenv("PG_POOL_OVERFLOW"), 20),
                _env_int(os.getenv("PG_POOL_IDLE"), 5), _env_int(os.getenv("PG_POOL_MAX_LIFETIME"), 1800),
                _env_int(os.getenv("PG_POOL_IDLE_SECONDS"), 300), _env_int(os.getenv("PG_POOL_TIMEOUT"), 30))

    def checkout(self):
        held = _held()
        nested = held.get(self.url, 0) > 0
        cap_base, cap_over, _keep, life, idle_s, timeout = self.limits()
        deadline = time.monotonic() + timeout
        with self.cond:
            while True:
                if nested and self.overflow < cap_over:
                    kind = "overflow"
                    self.overflow += 1
                    break
                if not nested and self.base < cap_base:
                    kind = "base"
                    self.base += 1
                    break
                left = deadline - time.monotonic()
                if left <= 0:
                    raise sqlite3.OperationalError(
                        f"database connection pool exhausted ({self.base} + {self.overflow} in use; "
                        f"PG_POOL_MAX={cap_base}, PG_POOL_OVERFLOW={cap_over})")
                self.cond.wait(left)
        _held_add(held, self.url, 1)
        try:
            raw = self._reuse(life, idle_s)
            if raw is None:
                raw = (self._connect(), time.monotonic())
                with self.cond:
                    self.opened += 1
            c = PgConnection(raw[0])
        except BaseException:
            self._give_back(kind, None, None)
            _held_add(held, self.url, -1)
            raise
        c._url, c._born, c._slot = self.url, raw[1], kind
        c._held = held
        return c

    # ── a database that restarts (DB-22, 10/19/26) ──────────────────────────
    #
    # Enabling point-in-time recovery redeployed production's Postgres: for
    # ~3 minutes every checkout opened a new connection and waited the whole
    # connect timeout (10 s) before failing, and the four request threads
    # queued behind those waits. Now a failed connect opens a short breaker
    # (PG_CONNECT_BACKOFF_S, 3 s): until it closes, a checkout that needs a
    # new connection fails at once, with the sqlite3.OperationalError every
    # caller already handles. And an idle connection is checked before it is
    # handed out — its own state always, a round trip when it has sat idle
    # past PG_POOL_PING_AFTER_S (30 s) — so a restart's dead connections are
    # dropped, never given to a request.

    def _reuse(self, life, idle_s):
        """A live idle connection as (raw, born), or None."""
        ping_after = _env_int(os.getenv("PG_POOL_PING_AFTER_S"), 30)
        while True:
            with self.cond:
                if not self.idle:
                    return None
                r, born, since = self.idle.pop()
            now = time.monotonic()
            if now - born <= life and now - since <= idle_s and _alive(r, ping=now - since > ping_after):
                return (r, born)
            with self.cond:
                self.opened -= 1
            _close_raw(r)

    def _connect(self):
        now = time.monotonic()
        if now < self.down_until:
            raise sqlite3.OperationalError(
                f"database unreachable (a connect failed {self.down_error}; retrying within "
                f"{max(0.0, self.down_until - now):.1f} s)")
        try:
            raw = _driver_connect(self.url)
        except Exception as e:
            self.down_until = time.monotonic() + _env_float(os.getenv("PG_CONNECT_BACKOFF_S"), 3.0)
            self.down_error = f"{type(e).__name__}: {str(e)[:200]}"
            raise sqlite3.OperationalError(f"database unreachable: {self.down_error}") from e
        self.down_until = 0.0
        return raw

    def checkin(self, conn):
        # The count of the thread that checked it out (closed from another
        # thread, it is still that thread's connection that ended).
        _held_add(getattr(conn, "_held", None) or _held(), self.url, -1)
        raw, keep = conn._raw, True
        try:
            raw.rollback()
        except Exception:
            keep = False
        if keep and getattr(getattr(raw, "info", None), "transaction_status", None) is not None and \
                getattr(raw.info.transaction_status, "name", "") != "IDLE":
            keep = False
        self._give_back(getattr(conn, "_slot", "base"), raw if keep else None, getattr(conn, "_born", 0),
                        drop=None if keep else raw)

    def _give_back(self, kind, raw, born, drop=None):
        _cb, _co, keep_n, life, _is, _t = self.limits()
        with self.cond:
            if kind == "overflow":
                self.overflow = max(0, self.overflow - 1)
            else:
                self.base = max(0, self.base - 1)
            if raw is not None and len(self.idle) < keep_n and time.monotonic() - born <= life:
                self.idle.append((raw, born, time.monotonic()))
                raw = None
            closing = raw or drop
            if closing is not None:
                self.opened -= 1
            self.cond.notify()
        if closing is not None:
            _close_raw(closing)

    def close_idle(self):
        with self.cond:
            idle, self.idle = self.idle, []
            self.opened -= len(idle)
        for r, _b, _s in idle:
            _close_raw(r)
        return len(idle)

    def stats(self):
        with self.cond:
            return {"in_use": self.base + self.overflow, "base": self.base, "overflow": self.overflow,
                    "idle": len(self.idle), "open": self.opened}


_pools = {}
_pools_lock = threading.Lock()
_local = threading.local()


def _held():
    h = getattr(_local, "held", None)
    if h is None:
        h = _local.held = {}
    return h


# A thread's held counts change from that thread (checkout, close) and from
# a collected connection's finalizer, which may run on another thread.
_held_lock = threading.Lock()


def _held_add(held, url, n):
    with _held_lock:
        held[url] = max(0, held.get(url, 0) + n)


def pool(url=None) -> "_Pool":
    url = url or database_url()
    with _pools_lock:
        p = _pools.get(url)
        if p is None:
            p = _pools[url] = _Pool(url)
        return p


def pool_stats(url=None) -> dict:
    """{in_use, base, overflow, idle, open} of this process's pool."""
    return pool(url).stats()


def close_idle(url=None) -> int:
    """Close the idle connections (every pool when `url` is None): before a
    database is used as a template, and at a process's end."""
    with _pools_lock:
        pools = [p for u, p in _pools.items() if url is None or u == url]
    return sum(p.close_idle() for p in pools)


def connect(url=None) -> PgConnection:
    """A PgConnection to `url` (DATABASE_URL by default), from the process's
    bounded pool (_Pool). close() hands it back; one never closed is handed
    back when it is collected."""
    url = url or database_url()
    if not url:
        raise sqlite3.OperationalError("DATABASE_URL is not a Postgres URL")
    p = pool(url)
    c = p.checkout()
    c._finalizer = weakref.finalize(c, _collected, p, c._raw, c._slot, c._born, c._held)
    return c


def _collected(p, raw, slot, born, held):
    """A PgConnection collected without close(): its transaction rolled
    back and the connection closed — never pooled (the thread that held it
    may be gone) — its slot freed, and its thread's held count taken down
    (it was not: that thread's every later checkout counted as nested and
    drew only overflow slots — blind re-audit 10/20/26 R2-13)."""
    try:
        raw.rollback()
    except Exception:
        pass
    _held_add(held, p.url, -1)
    p._give_back(slot, None, born, drop=raw)


def _close_raw(raw):
    try:
        raw.close()
    except Exception:
        pass


def _release(conn):
    fin = getattr(conn, "_finalizer", None)
    if fin is not None:
        fin.detach()
    p = _pools.get(getattr(conn, "_url", None))
    if p is None:
        try:
            conn._raw.rollback()
        except Exception:
            pass
        _close_raw(conn._raw)
        return
    p.checkin(conn)
