# ── tokenizer ───────────────────────────────────────────────────────────────

_TOKEN = re.compile(r"""
    (?P<dollar>\$\$.*?\$\$)
  | (?P<ws>\s+)
  | (?P<comment>--[^\n]*|/\*.*?\*/)
  | (?P<str>'(?:[^']|'')*')
  | (?P<qid>"(?:[^"]|"")*"|`[^`]*`|\[[^\]]*\])
  | (?P<param>\?\d*|:[A-Za-z_]\w*)
  | (?P<num>\d+(?:\.\d+)?)
  | (?P<word>[A-Za-z_][A-Za-z_0-9$]*)
  | (?P<op>\|\||<=|>=|<>|!=|==|::|[(),;.*=<>+\-/%])
  | (?P<other>.)
""", re.S | re.X)


class Tok:
    __slots__ = ("kind", "text")

    def __init__(self, kind, text):
        self.kind, self.text = kind, text

    def __repr__(self):
        return f"{self.kind}:{self.text}"

    @property
    def upper(self):
        return self.text.upper()


def tokenize(sql) -> list:
    out = []
    for m in _TOKEN.finditer(sql or ""):
        kind = m.lastgroup
        text = m.group(kind)
        if kind == "qid" and text[0] in "`[":
            text = '"' + text[1:-1] + '"'
        out.append(Tok(kind, text))
    return out


def _render(toks) -> str:
    return "".join(t.text for t in toks)


# A placeholder inside a rewritten function call, until the final pass
# turns it into psycopg's %s (after every literal % is doubled).
_P = "\x00P\x00"


def _render_marked(toks) -> str:
    return "".join(_P if t.kind == "param" else t.text for t in toks)


def _significant(toks):
    return [t for t in toks if t.kind not in ("ws", "comment")]


def _split_args(toks):
    """The top-level comma-separated arguments of a call's inside."""
    args, cur, depth = [], [], 0
    for t in toks:
        if t.kind == "op" and t.text == "(":
            depth += 1
        elif t.kind == "op" and t.text == ")":
            depth -= 1
        if t.kind == "op" and t.text == "," and depth == 0:
            args.append(cur)
            cur = []
            continue
        cur.append(t)
    if cur or args:
        args.append(cur)
    return args


def _call_end(toks, open_idx):
    """The index of the ')' closing the '(' at open_idx."""
    depth = 0
    for i in range(open_idx, len(toks)):
        t = toks[i]
        if t.kind == "op" and t.text == "(":
            depth += 1
        elif t.kind == "op" and t.text == ")":
            depth -= 1
            if depth == 0:
                return i
    raise TranslationError("unbalanced parentheses")


def _literal(arg):
    """The Python string of a single-string-literal argument, else None."""
    s = _significant(arg)
    if len(s) == 1 and s[0].kind == "str":
        return s[0].text[1:-1].replace("''", "'")
    return None


_INTERVAL = re.compile(r"^\s*([+-]?\d+(?:\.\d+)?)\s+(second|minute|hour|day|month|year)s?\s*$", re.I)


def _is_julian(arg) -> bool:
    """Whether a date function's time value is a Julian day number:
    julianday(…), or MAX / MIN / AVG of one."""
    sig = _significant(arg)
    k = 0
    while k + 1 < len(sig) and sig[k].kind == "word" and sig[k].upper in ("MAX", "MIN", "AVG") \
            and sig[k + 1].kind == "op" and sig[k + 1].text == "(":
        k += 2
    return k < len(sig) and sig[k].kind == "word" and sig[k].upper == "JULIANDAY"


def _timestamp(args, tr) -> str:
    """The timestamp expression for SQLite's (timevalue, modifiers...)."""
    if not args:
        raise TranslationError("a date function with no arguments")
    base = _literal(args[0])
    mods = args[1:]
    unix = any((_literal(m) or "").strip().lower() == "unixepoch" for m in mods)
    if base is not None and base.lower() == "now":
        expr = _NOW_TS
    elif _is_julian(args[0]):
        # datetime(MAX(julianday(x))): SQLite reads a number as a Julian day
        # (how the console orders mixed stamp formats as instants). As text
        # it was no date, so every owner's last sign-in and last request read
        # NULL on Postgres (blind re-audit 10/20/26 R9-02).
        expr = f"timezone('UTC', to_timestamp(({tr(args[0]).strip()} - 2440587.5) * 86400.0))"
    elif unix:
        expr = f"timezone('UTC', to_timestamp(CAST({tr(args[0]).strip()} AS double precision)))"
    else:
        # cavnar_ts (migrations/postgres/0000_sqlite_compat.sql): NULL for
        # '' or text that is no date, as SQLite's date('') is — a bare CAST
        # raised (SCALE-9); an offset honoured, the answer in UTC.
        expr = f"cavnar_ts(CAST({tr(args[0]).strip()} AS text))"
    for m in mods:
        lit = _literal(m)
        if lit is None:
            # A parameter (or an expression) holding '-5 minutes' and the like.
            expr = f"({expr} + CAST({tr(m).strip()} AS interval))"
            continue
        low = lit.strip().lower()
        if low in ("unixepoch", "localtime", "utc", ""):
            continue
        if low == "start of day":
            expr = f"date_trunc('day', {expr})"
        elif low == "start of month":
            expr = f"date_trunc('month', {expr})"
        elif low == "start of year":
            expr = f"date_trunc('year', {expr})"
        elif _INTERVAL.match(lit):
            expr = f"({expr} + interval '{lit.strip()}')"
        elif low.startswith("weekday "):
            n = int(low.split()[1])
            expr = (f"({expr} + ((({n} - CAST(extract(dow from {expr}) AS int)) + 7) % 7) * interval '1 day')")
        else:
            raise TranslationError(f"date modifier {lit!r} is not translated")
    return expr


_STRFTIME = {"%Y": "YYYY", "%m": "MM", "%d": "DD", "%H": "HH24", "%M": "MI", "%S": "SS", "%j": "DDD",
             "%f": "SS.MS", "%%": "%"}


def _strftime(args, tr) -> str:
    fmt = _literal(args[0]) if args else None
    if fmt is None:
        raise TranslationError("strftime with a format that is not a literal")
    ts = _timestamp(args[1:] or [[Tok("str", "'now'")]], tr)
    if fmt == "%s":
        return f"CAST(CAST(floor(extract(epoch from {ts})) AS bigint) AS text)"
    # SQLite's %W (week of the year, Monday first, 00-53) and %w (weekday,
    # Sunday 0) have no to_char pattern: computed, and the format becomes a
    # concatenation of to_char runs and those.
    special = {"%w": f"CAST(CAST(extract(dow from {ts}) AS int) AS text)",
               "%W": f"lpad(CAST(CAST(floor((extract(doy from {ts}) - 1 + 7 - "
                     f"((CAST(extract(dow from {ts}) AS int) + 6) % 7)) / 7) AS int) AS text), 2, '0')"}
    parts, run, i = [], [], 0

    def _flush():
        if run:
            parts.append(f"to_char({ts}, '{''.join(run)}')")
            run.clear()
    while i < len(fmt):
        two = fmt[i:i + 2]
        if two in special:
            _flush()
            parts.append(special[two])
            i += 2
            continue
        if two in _STRFTIME:
            run.append(_STRFTIME[two])
            i += 2
            continue
        if fmt[i] == "%":
            raise TranslationError(f"strftime format {fmt!r} is not translated")
        ch = fmt[i]
        run.append('"' + ch + '"' if ch.isalpha() else ch)
        i += 1
    _flush()
    if not parts:
        return "''"
    return parts[0] if len(parts) == 1 else "(" + " || ".join(parts) + ")"


def glob_regex(pattern) -> str:
    """A GLOB pattern as an anchored POSIX regex: * any run, ? one
    character, [...] a class ([^...] / [!...] negated), the rest literal."""
    out, i = ["^"], 0
    while i < len(pattern):
        c = pattern[i]
        if c == "*":
            out.append(".*")
        elif c == "?":
            out.append(".")
        elif c == "[":
            j = pattern.find("]", i + 1)
            if j == -1:
                out.append("\\[")
            else:
                body = pattern[i + 1:j]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append("[" + body + "]")
                i = j
        else:
            out.append(re.escape(c))
        i += 1
    out.append("$")
    return "".join(out)


