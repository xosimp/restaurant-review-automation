_TS_FMT = "'YYYY-MM-DD HH24:MI:SS'"
_NOW_TS = "timezone('UTC', now())"

# ── tokenizer ───────────────────────────────────────────────────────────────

_TOKEN = re.compile(r"""
    (?P<dollar>\$\$.*?\$\$)
  | (?P<ws>\s+)
  | (?P<comment>--[^\n]*|/\*.*?\*/)
  | (?P<str>'(?:[^']|'')*')
  | (?P<qid>"(?:[^"]|"")*"|`[^`]*`|\[[^\]]*\])
  | (?P<param>\?\d*|:[A-Za-z_]\w*)
  | (?P<num>\d+(?:\.\d+)?)
  | (?P<word>[A-Za-z_][A-Za-z_0-9$]*)
  | (?P<op>\|\||<=|>=|<>|!=|==|::|[(),;.*=<>+\-/%])
  | (?P<other>.)
""", re.S | re.X)


class Tok:
    __slots__ = ("kind", "text")

    def __init__(self, kind, text):
        self.kind, self.text = kind, text

    def __repr__(self):
        return f"{self.kind}:{self.text}"

    @property
    def upper(self):
        return self.text.upper()


def tokenize(sql) -> list:
    out = []
    for m in _TOKEN.finditer(sql or ""):
        kind = m.lastgroup
        text = m.group(kind)
        if kind == "qid" and text[0] in "`[":
            text = '"' + text[1:-1] + '"'
        out.append(Tok(kind, text))
    return out


def _render(toks) -> str:
    return "".join(t.text for t in toks)


# A placeholder inside a rewritten function call, until the final pass
# turns it into psycopg's %s (after every literal % is doubled).
_P = "\x00P\x00"


def _render_marked(toks) -> str:
    return "".join(_P if t.kind == "param" else t.text for t in toks)


def _significant(toks):
    return [t for t in toks if t.kind not in ("ws", "comment")]


def _split_args(toks):
    """The top-level comma-separated arguments of a call's inside."""
    args, cur, depth = [], [], 0
    for t in toks:
        if t.kind == "op" and t.text == "(":
            depth += 1
        elif t.kind == "op" and t.text == ")":
            depth -= 1
        if t.kind == "op" and t.text == "," and depth == 0:
            args.append(cur)
            cur = []
            continue
        cur.append(t)
    if cur or args:
        args.append(cur)
    return args


def _call_end(toks, open_idx):
    """The index of the ')' closing the '(' at open_idx."""
    depth = 0
    for i in range(open_idx, len(toks)):
        t = toks[i]
        if t.kind == "op" and t.text == "(":
            depth += 1
        elif t.kind == "op" and t.text == ")":
            depth -= 1
            if depth == 0:
                return i
    raise TranslationError("unbalanced parentheses")


def _literal(arg):
    """The Python string of a single-string-literal argument, else None."""
    s = _significant(arg)
    if len(s) == 1 and s[0].kind == "str":
        return s[0].text[1:-1].replace("''", "'")
    return None


_INTERVAL = re.compile(r"^\s*([+-]?\d+(?:\.\d+)?)\s+(second|minute|hour|day|month|year)s?\s*$", re.I)


def _timestamp(args, tr) -> str:
    """The timestamp expression for SQLite's (timevalue, modifiers...)."""
    if not args:
        raise TranslationError("a date function with no arguments")
    base = _literal(args[0])
    mods = args[1:]
    unix = any((_literal(m) or "").strip().lower() == "unixepoch" for m in mods)
    if base is not None and base.lower() == "now":
        expr = _NOW_TS
    elif unix:
        expr = f"timezone('UTC', to_timestamp(CAST({tr(args[0]).strip()} AS double precision)))"
    else:
        expr = f"CAST({tr(args[0]).strip()} AS timestamp)"
    for m in mods:
        lit = _literal(m)
        if lit is None:
            # A parameter (or an expression) holding '-5 minutes' and the like.
            expr = f"({expr} + CAST({tr(m).strip()} AS interval))"
            continue
        low = lit.strip().lower()
        if low in ("unixepoch", "localtime", "utc", ""):
            continue
        if low == "start of day":
            expr = f"date_trunc('day', {expr})"
        elif low == "start of month":
            expr = f"date_trunc('month', {expr})"
        elif low == "start of year":
            expr = f"date_trunc('year', {expr})"
        elif _INTERVAL.match(lit):
            expr = f"({expr} + interval '{lit.strip()}')"
        elif low.startswith("weekday "):
            n = int(low.split()[1])
            expr = (f"({expr} + ((({n} - CAST(extract(dow from {expr}) AS int)) + 7) % 7) * interval '1 day')")
        else:
            raise TranslationError(f"date modifier {lit!r} is not translated")
    return expr


_STRFTIME = {"%Y": "YYYY", "%m": "MM", "%d": "DD", "%H": "HH24", "%M": "MI", "%S": "SS", "%j": "DDD",
             "%f": "SS.MS", "%%": "%"}


def _strftime(args, tr) -> str:
    fmt = _literal(args[0]) if args else None
    if fmt is None:
        raise TranslationError("strftime with a format that is not a literal")
    ts = _timestamp(args[1:] or [[Tok("str", "'now'")]], tr)
    if fmt == "%s":
        return f"CAST(CAST(floor(extract(epoch from {ts})) AS bigint) AS text)"
    # SQLite's %W (week of the year, Monday first, 00-53) and %w (weekday,
    # Sunday 0) have no to_char pattern: computed, and the format becomes a
    # concatenation of to_char runs and those.
    special = {"%w": f"CAST(CAST(extract(dow from {ts}) AS int) AS text)",
               "%W": f"lpad(CAST(CAST(floor((extract(doy from {ts}) - 1 + 7 - "
                     f"((CAST(extract(dow from {ts}) AS int) + 6) % 7)) / 7) AS int) AS text), 2, '0')"}
    parts, run, i = [], [], 0

    def _flush():
        if run:
            parts.append(f"to_char({ts}, '{''.join(run)}')")
            run.clear()
    while i < len(fmt):
        two = fmt[i:i + 2]
        if two in special:
            _flush()
            parts.append(special[two])
            i += 2
            continue
        if two in _STRFTIME:
            run.append(_STRFTIME[two])
            i += 2
            continue
        if fmt[i] == "%":
            raise TranslationError(f"strftime format {fmt!r} is not translated")
        ch = fmt[i]
        run.append('"' + ch + '"' if ch.isalpha() else ch)
        i += 1
    _flush()
    if not parts:
        return "''"
    return parts[0] if len(parts) == 1 else "(" + " || ".join(parts) + ")"


def glob_regex(pattern) -> str:
    """A GLOB pattern as an anchored POSIX regex: * any run, ? one
    character, [...] a class ([^...] / [!...] negated), the rest literal."""
    out, i = ["^"], 0
    while i < len(pattern):
        c = pattern[i]
        if c == "*":
            out.append(".*")
        elif c == "?":
            out.append(".")
        elif c == "[":
            j = pattern.find("]", i + 1)
            if j == -1:
                out.append("\\[")
            else:
                body = pattern[i + 1:j]
                if body.startswith("!"):
                    body = "^" + body[1:]
                out.append("[" + body + "]")
                i = j
        else:
            out.append(re.escape(c))
        i += 1
    out.append("$")
    return "".join(out)


class Translator:
    """SQLite SQL -> Postgres SQL. `pk_lookup(table)` -> [primary key
    columns] (or None) — what INSERT OR REPLACE conflicts on and what rowid
    means; `columns_lookup(table)` -> [columns] for the DO UPDATE list."""

    def __init__(self, pk_lookup=None, columns_lookup=None):
        self.pk_lookup = pk_lookup or (lambda t: None)
        self.columns_lookup = columns_lookup or (lambda t: None)

    # Functions rewritten wherever they appear.
    def _rewrite(self, toks) -> list:
        out, i = [], 0
        while i < len(toks):
            t = toks[i]
            nxt = next((k for k in range(i + 1, len(toks)) if toks[k].kind not in ("ws", "comment")), None)
            is_call = t.kind == "word" and nxt is not None and toks[nxt].kind == "op" and toks[nxt].text == "("
            up = t.upper if t.kind == "word" else ""
            if is_call and up in ("DATETIME", "DATE", "TIME", "JULIANDAY", "STRFTIME", "IFNULL", "INSTR",
                                  "GROUP_CONCAT", "MAX", "MIN", "JSON_EXTRACT", "TOTAL"):
                end = _call_end(toks, nxt)
                inner = toks[nxt + 1:end]
                args = _split_args(inner)

                def tr(arg):
                    return _render_marked(self._rewrite(arg))
                rep = None
                if up == "DATETIME":
                    rep = f"to_char({_timestamp(args, tr)}, {_TS_FMT})"
                elif up == "DATE":
                    rep = f"to_char({_timestamp(args, tr)}, 'YYYY-MM-DD')"
                elif up == "TIME":
                    rep = f"to_char({_timestamp(args, tr)}, 'HH24:MI:SS')"
                elif up == "JULIANDAY":
                    rep = f"(extract(epoch from {_timestamp(args, tr)}) / 86400.0 + 2440587.5)"
                elif up == "STRFTIME":
                    rep = _strftime(args, tr)
                elif up == "IFNULL":
                    rep = "COALESCE(" + ",".join(tr(a) for a in args) + ")"
                elif up == "INSTR":
                    rep = "STRPOS(" + ",".join(tr(a) for a in args) + ")"
                elif up == "TOTAL":
                    rep = "COALESCE(SUM(" + tr(args[0]) + "), 0.0)"
                elif up == "GROUP_CONCAT":
                    sep = tr(args[1]) if len(args) > 1 else "','"
                    rep = f"string_agg(CAST({tr(args[0]).strip()} AS text), {sep.strip()})"
                elif up in ("MAX", "MIN") and len(args) >= 2:
                    rep = ("GREATEST(" if up == "MAX" else "LEAST(") + ",".join(tr(a) for a in args) + ")"
                elif up == "JSON_EXTRACT":
                    path = _literal(args[1]) if len(args) > 1 else None
                    if path is None or not path.startswith("$"):
                        raise TranslationError("json_extract with a path that is not a literal")
                    keys = [k for k in re.split(r"[.\[\]]+", path[1:]) if k]
                    rep = f"(CAST({tr(args[0]).strip()} AS jsonb) #>> '{{{','.join(keys)}}}')"
                if rep is not None:
                    out.append(Tok("other", rep))
                    i = end + 1
                    continue
            if t.kind == "word" and up == "NOTGLOB" and nxt is not None:
                pat = toks[nxt]
                if pat.kind == "str":
                    out.append(Tok("other", "!~ '" + glob_regex(pat.text[1:-1].replace("''", "'")).replace("'", "''")
                                   + "'"))
                    i = nxt + 1
                    continue
                if pat.kind == "param":
                    out.append(Tok("other", f"NOT LIKE replace(replace({_P}, '*', '%'), '?', '_')"))
                    i = nxt + 1
                    continue
                raise TranslationError("NOT GLOB with a pattern that is neither a literal nor a parameter")
            if t.kind == "word" and up == "GLOB" and nxt is not None:
                # x GLOB 'pattern' -> x ~ '^regex$' (case-sensitive, as GLOB
                # is); a parameter pattern of * and ? -> LIKE.
                pat = toks[nxt]
                if pat.kind == "str":
                    out.append(Tok("other", "~ '" + glob_regex(pat.text[1:-1].replace("''", "'")).replace("'", "''")
                                   + "'"))
                    i = nxt + 1
                    continue
                if pat.kind == "param":
                    out.append(Tok("other", f"LIKE replace(replace({_P}, '*', '%'), '?', '_')"))
                    i = nxt + 1
                    continue
                raise TranslationError("GLOB with a pattern that is neither a literal nor a parameter")
            if t.kind == "word" and up == "CURRENT_TIMESTAMP":
                out.append(Tok("other", f"to_char({_NOW_TS}, {_TS_FMT})"))
                i += 1
                continue
            out.append(t)
            i += 1
        return out

    def translate(self, sql) -> str:
        sql = re.sub(r"\bNOT\s+GLOB\b", "NOTGLOB", sql or "", flags=re.I)
        toks = tokenize(sql)
        sig = _significant(toks)
        if not sig:
            return sql
        head = [t.upper for t in sig[:4] if t.kind == "word"]
        if head[:1] == ["CREATE"] and "TABLE" in head:
            return self.translate_ddl(sql)
        toks = self._rewrite(toks)
        table = _main_table(_significant(toks))
        toks = self._statement(toks, table)
        out = []
        for t in toks:
            if t.kind == "param":
                out.append("%s")
            elif t.kind in ("str", "other", "op", "comment", "dollar"):
                out.append(t.text.replace("%", "%%").replace(_P, "%s"))
            elif t.kind == "word" and t.upper == "LIKE":
                out.append("ILIKE")
            elif t.kind == "word" and t.upper == "ROWID":
                pk = self.pk_lookup(table) if table else None
                out.append(pk[0] if pk and len(pk) == 1 else "ctid")
            else:
                out.append(t.text)
        return "".join(out).replace("LIMIT -1", "LIMIT ALL")

    def _statement(self, toks, table) -> list:
        """INSERT OR IGNORE / OR REPLACE / REPLACE INTO, and the partition
        column on an upsert's conflict target."""
        sig_idx = [i for i, t in enumerate(toks) if t.kind not in ("ws", "comment")]
        if not sig_idx:
            return toks
        first = toks[sig_idx[0]].upper
        mode = None
        if first == "INSERT" and len(sig_idx) > 2 and toks[sig_idx[1]].upper == "OR":
            mode = toks[sig_idx[2]].upper              # IGNORE | REPLACE
            for k in (sig_idx[1], sig_idx[2]):
                toks[k] = Tok("ws", "")
        elif first == "REPLACE":
            mode = "REPLACE"
            toks[sig_idx[0]] = Tok("word", "INSERT")
        part = PARTITIONED.get(table or "")
        if part:
            toks = _add_conflict_column(toks, part)
        if mode is None:
            return toks
        has_conflict = any(t.kind == "word" and t.upper == "CONFLICT" for t in toks)
        if has_conflict:
            return toks
        ret = next((i for i, t in enumerate(toks) if t.kind == "word" and t.upper == "RETURNING"), None)
        semi = next((i for i in range(len(toks) - 1, -1, -1) if toks[i].kind == "op" and toks[i].text == ";"), None)
        at = ret if ret is not None else (semi if semi is not None else len(toks))
        if mode == "IGNORE":
            clause = " ON CONFLICT DO NOTHING "
        else:
            pk = self.pk_lookup(table)
            if not pk:
                raise TranslationError(f"INSERT OR REPLACE into {table!r}: its primary key is unknown")
            cols = _insert_columns(toks) or self.columns_lookup(table) or []
            if part and part not in pk:
                pk = list(pk) + [part]
            upd = [c for c in cols if c not in pk]
            clause = (f" ON CONFLICT ({', '.join(pk)}) DO "
                      + (("UPDATE SET " + ", ".join(f"{c} = EXCLUDED.{c}" for c in upd)) if upd else "NOTHING") + " ")
        return toks[:at] + [Tok("other", clause)] + toks[at:]

    def translate_ddl(self, sql) -> str:
        """CREATE TABLE in SQLite's types -> Postgres's."""
        toks = self._rewrite(tokenize(sql))
        text = _render(toks)
        text = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
                      "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", text, flags=re.I)
        text = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\b(?!\s*\()",
                      "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", text, flags=re.I)
        text = re.sub(r"\bAUTOINCREMENT\b", "", text, flags=re.I)
        text = re.sub(r"\bINTEGER\b", "BIGINT", text, flags=re.I)
        text = re.sub(r"\bREAL\b", "DOUBLE PRECISION", text, flags=re.I)
        text = re.sub(r"\bBLOB\b", "BYTEA", text, flags=re.I)
        text = re.sub(r"\bCOLLATE\s+NOCASE\b", "", text, flags=re.I)
        text = re.sub(r"\)\s*WITHOUT\s+ROWID\s*$", ")", text.strip(), flags=re.I)
        return text


def _main_table(sig):
    """The table a statement writes or reads first (INSERT INTO t, UPDATE t,
    DELETE FROM t, … FROM t)."""
    for i, t in enumerate(sig):
        if t.kind == "word" and t.upper in ("INTO", "UPDATE", "FROM") and i + 1 < len(sig):
            nxt = sig[i + 1]
            if nxt.kind in ("word", "qid") and nxt.upper not in ("SELECT",):
                return nxt.text.strip('"').lower()
    return None


def _insert_columns(toks):
    sig = _significant(toks)
    for i, t in enumerate(sig):
        if t.kind == "word" and t.upper == "INTO" and i + 2 < len(sig) and sig[i + 2].text == "(":
            cols, j = [], i + 3
            while j < len(sig) and sig[j].text != ")":
                if sig[j].kind in ("word", "qid"):
                    cols.append(sig[j].text.strip('"'))
                j += 1
            return cols
    return None


def _add_conflict_column(toks, column):
    """ON CONFLICT (a, b) on a partitioned table -> ON CONFLICT (a, b, col)."""
    for i, t in enumerate(toks):
        if t.kind == "word" and t.upper == "CONFLICT":
            j = i + 1
            while j < len(toks) and toks[j].kind in ("ws", "comment"):
                j += 1
            if j < len(toks) and toks[j].text == "(":
                end = _call_end(toks, j)
                names = [x.text.strip('"').lower() for x in toks[j + 1:end] if x.kind in ("word", "qid")]
                if column not in names:
                    return toks[:end] + [Tok("other", f", {column}")] + toks[end:]
            return toks
    return toks


