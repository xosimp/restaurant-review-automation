"""
db_dialect.py — the database behind models.get_conn: SQLite (the default,
as always), or Postgres when DATABASE_URL names one (scheduler audit
10/10/26: RM-13, RM-14, SCALE-20, SCALE-21, ARCH-34;
docs/plans/POSTGRES_AND_WORKERS_PLAN.md step 3; the cutover runbook is
docs/ops/POSTGRES_CUTOVER.md).

The app speaks SQLite's SQL in ~1,500 get_conn() call sites. Rather than
1,500 hand edits, this module makes a Postgres connection behave as the app
expects a sqlite3 connection to, and translates each statement on its way:

  TRANSLATION (translate): `?` placeholders -> `%s` (a literal `%` doubled);
  datetime()/date()/time()/julianday()/strftime() — 'now', a column, an
  expression, with their modifiers ('-5 minutes', ?, 'start of day',
  'start of month', 'unixepoch', 'localtime' / 'utc') — into to_char /
  extract(epoch) over timezone('UTC', now()) or CAST(x AS timestamp), so a
  TEXT stamp still reads 'YYYY-MM-DD HH:MM:SS' and every stored comparison
  holds; CURRENT_TIMESTAMP likewise; INSERT OR IGNORE -> ON CONFLICT DO
  NOTHING; INSERT OR REPLACE / REPLACE INTO -> ON CONFLICT (primary key) DO
  UPDATE; scalar MAX(a, b) / MIN(a, b) -> GREATEST / LEAST; IFNULL ->
  COALESCE; INSTR -> STRPOS; GROUP_CONCAT -> string_agg; json_extract(x,
  '$.a.b') -> (x::jsonb #>> '{a,b}'); LIKE -> ILIKE (SQLite's LIKE ignores
  ASCII case); rowid -> the table's integer primary key, else ctid;
  LIMIT -1 -> LIMIT ALL; the conflict target of an upsert into a
  month-partitioned fact table gains its partition column (PARTITIONED).
  DDL (translate_ddl): INTEGER PRIMARY KEY [AUTOINCREMENT] -> BIGINT
  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, INTEGER -> BIGINT, REAL ->
  DOUBLE PRECISION, BLOB -> BYTEA, COLLATE NOCASE and WITHOUT ROWID dropped,
  defaults translated.

  THE CONNECTION (PgConnection, over psycopg 3): execute / executemany /
  executescript / commit / rollback / close / `with conn:` as sqlite3's;
  rows readable by name and position (PgRow, like sqlite3.Row); `lastrowid`
  from a RETURNING the wrapper adds; `rowcount`. `BEGIN IMMEDIATE` (the
  claim-before-work and compare-and-set paths: claims, the lease, the
  job queue, owed sends) takes a transaction-scoped advisory lock — the one
  writer SQLite had, kept for exactly the code that relied on it. PRAGMAs:
  table_info / index_list answered from the catalog, integrity_check "ok",
  the rest (foreign_keys, journal_mode, synchronous, busy_timeout, optimize,
  wal_checkpoint) no-ops. sqlite_master is a view the base migration
  creates over the catalog (migrations/postgres/0000_sqlite_compat.sql).
  Errors arrive as sqlite3.IntegrityError / sqlite3.OperationalError, so
  every `except sqlite3.…` keeps working. Connections are reused per thread.

What it cannot translate it leaves alone, and Postgres refuses it loudly;
scripts/pg_sql_audit.py lists every SQL literal in the code a translation
would not carry (double-quoted strings, unsupported strftime formats,
typeof, printf) — the remaining port is that list, not a guess.

SQLite stays the default: backend() is "postgres" only when DATABASE_URL is
a postgres:// URL and DB_BACKEND is not "sqlite". The shadow (pg_shadow)
writes to SHADOW_DATABASE_URL instead, while SQLite remains the primary.
"""
