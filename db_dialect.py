class PgRow:
    """A result row readable as sqlite3.Row is: by position, by column name
    (any case), keys(), len, iteration over values; dict(row) works."""
    __slots__ = ("_values", "_names", "_index")

    def __init__(self, values, names):
        self._values = tuple(values)
        self._names = list(names)
        self._index = {n.lower(): i for i, n in enumerate(names)}

    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return self._values[key]
        try:
            return self._values[self._index[str(key).lower()]]
        except KeyError:
            raise IndexError(f"No item with that key: {key}")

    def keys(self):
        return list(self._names)

    def __len__(self):
        return len(self._values)

    def __iter__(self):
        return iter(self._values)

    def __eq__(self, other):
        return isinstance(other, PgRow) and other._values == self._values and other._names == self._names

    def __repr__(self):
        return f"PgRow({dict(zip(self._names, self._values))})"


class PgCursor:
    def __init__(self, conn, raw):
        self._conn, self._raw = conn, raw
        self._rows, self._pos = None, 0
        self.rowcount, self.lastrowid, self.description = -1, None, None

    def _load(self, rows=None, description=None):
        self.description = description
        names = [d[0] for d in (description or [])]
        self._rows = [PgRow(r, names) for r in (rows or [])]
        self._pos = 0

    def fetchone(self):
        if not self._rows or self._pos >= len(self._rows):
            return None
        r = self._rows[self._pos]
        self._pos += 1
        return r

    def fetchall(self):
        if not self._rows:
            return []
        out = self._rows[self._pos:]
        self._pos = len(self._rows)
        return out

    def fetchmany(self, size=1):
        out = (self._rows or [])[self._pos:self._pos + size]
        self._pos += len(out)
        return out

    def __iter__(self):
        while True:
            r = self.fetchone()
            if r is None:
                return
            yield r

    def close(self):
        pass

    def execute(self, sql, params=()):
        return self._conn.execute(sql, params, _cursor=self)


def _map_error(e):
    """A driver error as the sqlite3 error the app's except clauses expect."""
    name = type(e).__name__
    try:
        import psycopg
        if isinstance(e, psycopg.errors.IntegrityError):
            return sqlite3.IntegrityError(str(e))
    except ImportError:
        pass
    if "Integrity" in name or "UniqueViolation" in name or "ForeignKeyViolation" in name or \
            "NotNullViolation" in name or "CheckViolation" in name:
        return sqlite3.IntegrityError(str(e))
    msg = str(e)
    if "UndefinedTable" in name or "does not exist" in msg:
        return sqlite3.OperationalError(f"no such table or column: {msg}")
    return sqlite3.OperationalError(msg)


_PRAGMA = re.compile(r"^\s*PRAGMA\s+(\w+)\s*(?:\(\s*['\"]?(\w+)['\"]?\s*\)|=\s*(\S+))?\s*;?\s*$", re.I)
_BEGIN = re.compile(r"^\s*BEGIN(\s+(DEFERRED|IMMEDIATE|EXCLUSIVE))?(\s+TRANSACTION)?\s*;?\s*$", re.I)
_TRIGGER = re.compile(r"^\s*(CREATE|DROP)\s+TRIGGER\b", re.I)
_END = re.compile(r"^\s*(COMMIT|END|ROLLBACK)(\s+TRANSACTION)?\s*;?\s*$", re.I)


class PgConnection:
    """A Postgres connection with the sqlite3.Connection surface the app
    uses. `raw` is a DB-API connection (psycopg's)."""

    def __init__(self, raw, catalog=None):
        self._raw = raw
        self._closed = False
        self._catalog = catalog or Catalog(raw)
        self._tr = Translator(self._catalog.primary_key, self._catalog.columns)
        self.row_factory = None
        self.isolation_level = ""
        self.text_factory = str
        self._in_tx = False

    # sqlite3.Connection's attributes the app reads
    @property
    def in_transaction(self):
        return self._in_tx

    @property
    def total_changes(self):
        return 0

    def cursor(self):
        return PgCursor(self, None)

    def _special(self, sql, cur):
        m = _BEGIN.match(sql)
        if m:
            self._in_tx = True
            if (m.group(2) or "").upper() in ("IMMEDIATE", "EXCLUSIVE"):
                self._run("SELECT pg_advisory_xact_lock(%s)", (WRITE_LOCK_KEY,), cur)
            cur._load()
            return True
        m = _END.match(sql)
        if m:
            (self.rollback if m.group(1).upper() == "ROLLBACK" else self.commit)()
            cur._load()
            return True
        if _TRIGGER.match(sql):
            # SQLite's triggers (the boot's tracker change stamps, the intel
            # features version) are ported as plpgsql once, by the copy
            # (migrations/postgres/0002_triggers.sql); the boot's own
            # DROP/CREATE TRIGGER is not Postgres's syntax.
            cur._load()
            return True
        m = _PRAGMA.match(sql)
        if m:
            name = m.group(1).lower()
            arg = m.group(2)
            if name == "table_info" and arg:
                cur._load(self._catalog.table_info(arg), [("cid",), ("name",), ("type",), ("notnull",),
                                                          ("dflt_value",), ("pk",)])
            elif name == "index_list" and arg:
                cur._load(self._catalog.index_list(arg), [("seq",), ("name",), ("unique",), ("origin",),
                                                          ("partial",)])
            elif name in ("integrity_check", "quick_check"):
                cur._load([("ok",)], [(name,)])
            elif name == "journal_mode":
                cur._load([("wal",)], [("journal_mode",)])
            elif name == "foreign_key_check":
                cur._load([], [("table",)])
            elif name == "database_list":
                cur._load([(0, "main", "")], [("seq",), ("name",), ("file",)])
            elif name == "schema_version":
                self._run("SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = current_schema()",
                          (), cur)
            else:
                cur._load([], [])
            return True
        return False

    def _run(self, sql, params, cur):
        try:
            raw = self._raw.cursor()
            # Always a tuple: every literal % was doubled, so the query is
            # always read for placeholders (never sent with params=None).
            raw.execute(sql, tuple(params or ()))
            self._in_tx = True
            rows = raw.fetchall() if raw.description else []
            cur._load(rows, raw.description)
            cur.rowcount = raw.rowcount
            return raw
        except Exception as e:
            raise _map_error(e) from e

    def execute(self, sql, params=(), _cursor=None):
        if self._closed:
            raise sqlite3.ProgrammingError("Cannot operate on a closed database.")
        cur = _cursor or PgCursor(self, None)
        if self._special(sql, cur):
            return cur
        try:
            text = self._tr.translate(sql)
        except TranslationError as e:
            raise sqlite3.OperationalError(f"not translatable to Postgres: {e}") from e
        sig = _significant(tokenize(text))
        is_insert = bool(sig) and sig[0].upper == "INSERT"
        if is_insert and not any(t.kind == "word" and t.upper == "RETURNING" for t in sig):
            table = _main_table(sig)
            pk = self._catalog.primary_key(table) if table else None
            if pk and len(pk) == 1 and self._catalog.is_integer(table, pk[0]):
                text = text.rstrip().rstrip(";") + f" RETURNING {pk[0]}"
                self._run(text, params, cur)
                got = cur.fetchone()
                cur.lastrowid = got[0] if got else None
                cur._rows, cur._pos = [], 0
                return cur
        self._run(text, params, cur)
        return cur

    def executemany(self, sql, seq):
        cur = PgCursor(self, None)
        total = 0
        for params in seq:
            self.execute(sql, params, _cursor=cur)
            total += max(0, cur.rowcount or 0)
        cur.rowcount = total
        return cur

    def executescript(self, script):
        for stmt in split_statements(script):
            self.execute(stmt)
        return PgCursor(self, None)

    def commit(self):
        try:
            self._raw.commit()
        except Exception as e:
            raise _map_error(e) from e
        self._in_tx = False

    def rollback(self):
        try:
            self._raw.rollback()
        except Exception as e:
            raise _map_error(e) from e
        self._in_tx = False

    def close(self):
        if self._closed:
            return
        self._closed = True
        _release(self)

    def create_function(self, *a, **k):
        raise sqlite3.NotSupportedError("custom SQL functions are SQLite-only")

    def __enter__(self):
        return self

    def __exit__(self, et, ev, tb):
        if et is None:
            self.commit()
        else:
            self.rollback()
        return False


def split_statements(script) -> list:
    """`script` split on top-level semicolons (never inside a string)."""
    out, cur = [], []
    for t in tokenize(script):
        if t.kind == "op" and t.text == ";":
            s = _render(cur).strip()
            if s:
                out.append(s)
            cur = []
        else:
            cur.append(t)
    s = _render(cur).strip()
    if s:
        out.append(s)
    return out


class Catalog:
    """Primary keys, columns and integer-ness of the tables, read from
    information_schema once per table per process."""
    _shared = {}
    _lock = threading.Lock()

    def __init__(self, raw):
        self._raw = raw

    def _q(self, sql, params):
        c = self._raw.cursor()
        c.execute(sql, params)
        return c.fetchall()

    def _info(self, table):
        key = str(table or "").lower()
        with Catalog._lock:
            hit = Catalog._shared.get(key)
        if hit is not None:
            return hit
        try:
            cols = self._q("SELECT column_name, data_type, is_nullable, column_default, ordinal_position "
                           "FROM information_schema.columns WHERE table_schema = current_schema() "
                           "AND table_name = %s ORDER BY ordinal_position", (key,))
            pk = [r[0] for r in self._q(
                "SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid "
                "AND a.attnum = ANY(i.indkey) WHERE i.indrelid = to_regclass(%s) AND i.indisprimary "
                "ORDER BY array_position(i.indkey, a.attnum)", (key,))]
        except Exception:
            try:
                self._raw.rollback()
            except Exception:
                pass
            return {"columns": [], "pk": [], "types": {}}
        info = {"columns": [r[0] for r in cols], "pk": pk, "types": {r[0]: r[1] for r in cols},
                "rows": cols}
        with Catalog._lock:
            Catalog._shared[key] = info
        return info

    @classmethod
    def forget(cls, table=None):
        with cls._lock:
            if table is None:
                cls._shared.clear()
            else:
                cls._shared.pop(str(table).lower(), None)

    def primary_key(self, table):
        return self._info(table)["pk"] or None if table else None

    def columns(self, table):
        return self._info(table)["columns"] or None if table else None

    def is_integer(self, table, column):
        return self._info(table)["types"].get(column) in ("integer", "bigint", "smallint")

    def table_info(self, table):
        info = self._info(table)
        out = []
        for i, (name, dtype, nullable, default, _pos) in enumerate(info.get("rows") or []):
            out.append((i, name, dtype.upper(), 0 if nullable == "YES" else 1, default,
                        (info["pk"].index(name) + 1) if name in info["pk"] else 0))
        return out

    def index_list(self, table):
        rows = self._q("SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = current_schema() "
                       "AND tablename = %s", (str(table).lower(),))
        return [(i, r[0], 1 if "UNIQUE" in r[1].upper() else 0, "c", 1 if " WHERE " in r[1].upper() else 0)
                for i, r in enumerate(rows)]


# ── connections, reused per thread ──────────────────────────────────────────

_local = threading.local()
_POOL_PER_THREAD = 3


def _driver_connect(url):
    import psycopg
    return psycopg.connect(url, autocommit=False, connect_timeout=10)


def connect(url=None) -> PgConnection:
    """A PgConnection to `url` (DATABASE_URL by default), reused from this
    thread's idle ones when one is open and idle."""
    url = url or database_url()
    if not url:
        raise sqlite3.OperationalError("DATABASE_URL is not a Postgres URL")
    idle = getattr(_local, "idle", None)
    if idle is None:
        idle = _local.idle = []
    while idle:
        u, raw = idle.pop()
        if u != url:
            _close_raw(raw)
            continue
        try:
            raw.rollback()
            c = PgConnection(raw)
            c._url = url
            return c
        except Exception:
            _close_raw(raw)
    c = PgConnection(_driver_connect(url))
    c._url = url
    return c


def _close_raw(raw):
    try:
        raw.close()
    except Exception:
        pass


def _release(conn):
    raw = conn._raw
    try:
        raw.rollback()
    except Exception:
        _close_raw(raw)
        return
    idle = getattr(_local, "idle", None)
    if idle is None:
        idle = _local.idle = []
    if len(idle) >= _POOL_PER_THREAD:
        _close_raw(raw)
        return
    idle.append((getattr(conn, "_url", None), raw))
