def database_url(name="DATABASE_URL"):
    url = (os.getenv(name) or "").strip()
    return url if url.startswith(("postgres://", "postgresql://")) else None


def backend() -> str:
    """"postgres" when DATABASE_URL names a Postgres database (and
    DB_BACKEND does not pin "sqlite"), else "sqlite"."""
    if (os.getenv("DB_BACKEND") or "").strip().lower() == "sqlite":
        return "sqlite"
    return "postgres" if database_url() else "sqlite"


