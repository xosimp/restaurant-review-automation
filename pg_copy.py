"""
pg_copy.py — the database copied between SQLite and Postgres, and proved
(scheduler audit 10/10/26: RM-14, SCALE-20, ARCH-34; the steps are in
docs/ops/POSTGRES_CUTOVER.md).

  plan / schema: every table and index of the SQLite file, in Postgres's
  types (db_dialect.Translator.translate_ddl). The fact tables in
  db_dialect.PARTITIONED are created PARTITION BY RANGE on their date
  column, one partition a month from the oldest row to MONTHS_AHEAD past
  today plus a DEFAULT partition, their primary key and UNIQUE constraints
  carrying the partition column (Postgres requires it); their ids come
  from a sequence. Then the compatibility view (migrations/postgres/
  0000_sqlite_compat.sql) and the normalized schedule model
  (0001_schedule_model.sql).

  copy_table: rows in batches, each value made what its column's type takes
  — '' or text that is no number in an INTEGER / REAL column becomes NULL
  and is COUNTED (SQLite stores whatever it is given; Postgres does not),
  a NULL partition key becomes PARTITION_NULL_SENTINEL (counted) — then
  each identity / sequence set past the highest id.

  verify: every table's row count on both sides and, for an integer primary
  key, its min, max and sum — the copy is "verified" only when every table
  matches. The report (JSON) is what the cutover runbook checks.

  export_to_sqlite: the other direction — a consistent snapshot of the
  Postgres database (one REPEATABLE READ transaction) written into a fresh
  SQLite file built by the app's own boot migrations (models.init_db):
  the nightly backup on Postgres (scheduler._write_consistent_snapshot),
  so the scrubbed, encrypted off-site copy is made from a restored copy and
  never the live database, and the rollback path of the cutover.
"""
import json
import os
import re
import sqlite3
import time
from datetime import date

import db_dialect

BATCH_ROWS = int(os.getenv("PG_COPY_BATCH_ROWS", "2000"))
MONTHS_AHEAD = 3
PARTITION_NULL_SENTINEL = "1970-01-01 00:00:00"
_SKIP = re.compile(r"^sqlite_")
MIGRATIONS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "migrations", "postgres")


# ── the plan ────────────────────────────────────────────────────────────────

def sqlite_tables(src) -> list:
    """[(name, create sql)] of the SQLite database's own tables."""
    return [(r[0], r[1]) for r in src.execute("SELECT name, sql FROM sqlite_master WHERE type='table' "
                                              "AND sql IS NOT NULL ORDER BY name").fetchall()
            if not _SKIP.match(r[0])]


def sqlite_indexes(src) -> list:
    return [(r[0], r[1], r[2]) for r in src.execute(
        "SELECT name, tbl_name, sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name")
            if not _SKIP.match(r[1])]


def table_columns(src, table) -> list:
    """[(name, declared type upper, pk position)] in order."""
    return [(r[1], (r[2] or "").upper(), int(r[5] or 0))
            for r in src.execute(f'PRAGMA table_info("{table}")').fetchall()]


def _elements(ddl):
    """(head, [element texts], tail) of a CREATE TABLE: the text up to its
    opening '(', each top-level column / constraint, the rest after ')'."""
    toks = db_dialect.tokenize(ddl)
    open_i = next(i for i, t in enumerate(toks) if t.kind == "op" and t.text == "(")
    close_i = db_dialect._call_end(toks, open_i)
    parts = db_dialect._split_args(toks[open_i + 1:close_i])
    return (db_dialect._render(toks[:open_i]), [db_dialect._render(p).strip() for p in parts],
            db_dialect._render(toks[close_i + 1:]))


_REF = re.compile(r"\bREFERENCES\b.*$", re.I | re.S)


def table_ddl(name, sql, partition_col=None) -> tuple:
    """(statements that create `name`, statements to run after the data is
    in): the table in Postgres's types — a partitioned table's sequence, the
    table PARTITION BY RANGE, its DEFAULT partition — and its foreign keys
    as ALTER TABLE … ADD FOREIGN KEY, added once every table holds its rows
    (rows copied in any order, and a self-reference — people.merged_into —
    pointing forward, never trip them)."""
    ddl = db_dialect.Translator().translate_ddl(sql)
    head, elems, tail = _elements(ddl)
    keep, fks = [], []
    for e in elems:
        if re.match(r"(CONSTRAINT\s+\S+\s+)?FOREIGN\s+KEY\b", e, re.I):
            fks.append(e)
            continue
        m = _REF.search(e)
        if m and not re.match(r"(CONSTRAINT|PRIMARY|UNIQUE|CHECK)\b", e, re.I):
            col = e.split()[0]
            fks.append(f"FOREIGN KEY ({col}) {m.group(0).strip()}")
            e = e[:m.start()].rstrip()
        keep.append(e)
    pre = []
    if partition_col:
        seq = f"{name}_id_seq"
        out = []
        for e in keep:
            if re.match(r"id\s+BIGINT\s+GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", e, re.I):
                pre.append(f"CREATE SEQUENCE IF NOT EXISTS {seq}")
                out.append(f"id BIGINT NOT NULL DEFAULT nextval('{seq}')")
                out.append(f"PRIMARY KEY (id, {partition_col})")
                continue
            m = re.match(r"((?:CONSTRAINT\s+\S+\s+)?(?:PRIMARY\s+KEY|UNIQUE)\s*)\(([^)]*)\)(.*)$", e, re.I | re.S)
            if m:
                cols = [c.strip() for c in m.group(2).split(",")]
                if partition_col not in [c.strip('"').lower() for c in cols]:
                    cols.append(partition_col)
                e = f"{m.group(1)}({', '.join(cols)}){m.group(3)}"
            out.append(e)
        keep = out
    head = re.sub(r"^\s*CREATE\s+TABLE\s+(?!IF\s)", "CREATE TABLE IF NOT EXISTS ", head, flags=re.I)
    body = head + "(\n    " + ",\n    ".join(keep) + "\n)" + tail.rstrip().rstrip(";")
    if partition_col:
        body += f" PARTITION BY RANGE ({partition_col})"
    pre.append(body)
    if partition_col:
        pre.append(f"CREATE TABLE IF NOT EXISTS {name}_default PARTITION OF {name} DEFAULT")
    post = [f"ALTER TABLE {name} ADD {fk}" for fk in fks]
    return pre, post


def index_ddl(sql, table=None) -> str:
    """A CREATE INDEX in Postgres's SQL; a UNIQUE index on a partitioned
    table gains the partition column."""
    text = db_dialect.Translator().translate(sql).replace("%%", "%")
    text = re.sub(r"^\s*CREATE\s+(UNIQUE\s+)?INDEX\s+(?!IF\s)", lambda m: f"CREATE {m.group(1) or ''}INDEX IF NOT EXISTS ",
                  text, flags=re.I)
    part = db_dialect.PARTITIONED.get((table or "").lower())
    if part and re.match(r"\s*CREATE\s+UNIQUE", text, re.I):
        text = re.sub(r"\(([^)]*)\)", lambda m: m.group(0) if part in m.group(1) else
                      f"({m.group(1)}, {part})", text, count=1)
    return text


def month_bounds(first, last) -> list:
    """[(from 'YYYY-MM-01', to 'YYYY-MM-01')] one a month, first..last."""
    y, m = first.year, first.month
    out = []
    while (y, m) <= (last.year, last.month):
        ny, nm = (y + 1, 1) if m == 12 else (y, m + 1)
        out.append((f"{y:04d}-{m:02d}-01", f"{ny:04d}-{nm:02d}-01"))
        y, m = ny, nm
    return out


def partition_ddl(table, first, last) -> list:
    """A partition per month of `table` from `first` to `last` (dates)."""
    return [f"CREATE TABLE IF NOT EXISTS {table}_p{a[:4]}{a[5:7]} PARTITION OF {table} "
            f"FOR VALUES FROM ('{a}') TO ('{b}')" for a, b in month_bounds(first, last)]


def _first_date(src, table, col):
    try:
        v = src.execute(f'SELECT MIN({col}) FROM "{table}" WHERE {col} IS NOT NULL AND {col} >= \'1971\'').fetchone()[0]
        return date.fromisoformat(str(v)[:10]) if v else None
    except Exception:
        return None


def _add_months(d, n):
    m = d.month - 1 + n
    return date(d.year + m // 12, m % 12 + 1, 1)


def schema_statements(src, today=None) -> list:
    """Every statement that builds the Postgres schema for this SQLite file,
    in order: the compatibility view, tables, partitions, indexes, the
    normalized schedule model."""
    return schema_plan(src, today)["before"]


def schema_plan(src, today=None) -> dict:
    """{"before": statements before the rows (the compatibility view, every
    table and partition, the indexes, the normalized model, the triggers),
    "after": statements once the rows are in (the foreign keys)}."""
    today = today or date.today()
    out = [_read_migration("0000_sqlite_compat.sql")]
    after = []
    names = set()
    for name, sql in sqlite_tables(src):
        names.add(name)
        part = db_dialect.PARTITIONED.get(name)
        pre, post = table_ddl(name, sql, part)
        out.extend(pre)
        after.extend(post)
        if part:
            first = _first_date(src, name, part) or today
            out.extend(partition_ddl(name, date(first.year, first.month, 1), _add_months(today, MONTHS_AHEAD)))
    for _iname, tbl, sql in sqlite_indexes(src):
        if tbl in names:
            out.append(index_ddl(sql, tbl))
    out.append(_read_migration("0001_schedule_model.sql"))
    out.extend(trigger_statements(src))
    return {"before": out, "after": after}


def trigger_statements(src) -> list:
    """SQLite's triggers, ported (migrations/postgres/0002_triggers.sql is
    this function's output for the current schema): the tracker's change
    stamp (models.ensure_tracker_change_stamps — changed_at on an insert,
    and on an update of a learning column) and the intel features' version
    default (intelligence.features). The boot's own DROP/CREATE TRIGGER is a
    no-op on Postgres (db_dialect.PgConnection)."""
    out = []
    have = {c[0] for c in table_columns(src, "recommendation_outcomes")} if \
        src.execute("SELECT 1 FROM sqlite_master WHERE name='recommendation_outcomes'").fetchone() else set()
    if "changed_at" in have:
        import models
        watched = [c for c in models.TRACKER_LEARNING_COLUMNS if c in have]
        out.append("CREATE OR REPLACE FUNCTION cavnar_outcomes_changed() RETURNS trigger LANGUAGE plpgsql AS $$ "
                   "BEGIN NEW.changed_at := to_char(timezone('UTC', clock_timestamp()), "
                   "'YYYY-MM-DD HH24:MI:SS.MS'); RETURN NEW; END $$")
        out.append("DROP TRIGGER IF EXISTS trg_outcomes_changed_ins ON recommendation_outcomes")
        out.append("CREATE TRIGGER trg_outcomes_changed_ins BEFORE INSERT ON recommendation_outcomes "
                   "FOR EACH ROW EXECUTE FUNCTION cavnar_outcomes_changed()")
        if watched:
            when = " OR ".join(f"NEW.{c} IS DISTINCT FROM OLD.{c}" for c in watched)
            out.append("DROP TRIGGER IF EXISTS trg_outcomes_changed_upd ON recommendation_outcomes")
            out.append(f"CREATE TRIGGER trg_outcomes_changed_upd BEFORE UPDATE ON recommendation_outcomes "
                       f"FOR EACH ROW WHEN ({when}) EXECUTE FUNCTION cavnar_outcomes_changed()")
    if src.execute("SELECT 1 FROM sqlite_master WHERE name='intel_features'").fetchone() and \
            "version" in {c[0] for c in table_columns(src, "intel_features")}:
        from intelligence.features import FEATURES_VERSION
        out.append("CREATE OR REPLACE FUNCTION cavnar_intel_features_version() RETURNS trigger LANGUAGE plpgsql AS "
                   f"$$ BEGIN NEW.version := {int(FEATURES_VERSION)}; RETURN NEW; END $$")
        out.append("DROP TRIGGER IF EXISTS trg_intel_features_version ON intel_features")
        out.append("CREATE TRIGGER trg_intel_features_version BEFORE INSERT ON intel_features FOR EACH ROW "
                   "WHEN (NEW.version IS NULL) EXECUTE FUNCTION cavnar_intel_features_version()")
    return out


def _read_migration(name):
    with open(os.path.join(MIGRATIONS_DIR, name), encoding="utf-8") as f:
        return f.read()


# ── copying ─────────────────────────────────────────────────────────────────

def _coerce(value, coltype, is_partition, counts, key):
    if is_partition and value in (None, ""):
        counts[key] = counts.get(key, 0) + 1
        return PARTITION_NULL_SENTINEL
    if value is None:
        return None
    if "INT" in coltype:
        if isinstance(value, bool):
            return int(value)
        if isinstance(value, int):
            return value
        if isinstance(value, float) and value.is_integer():
            return int(value)
        try:
            return int(str(value).strip())
        except (TypeError, ValueError):
            try:
                f = float(str(value).strip())
                if f.is_integer():
                    return int(f)
            except (TypeError, ValueError):
                pass
        counts[key] = counts.get(key, 0) + 1
        return None
    if "REAL" in coltype or "FLOA" in coltype or "DOUB" in coltype:
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return float(value)
        try:
            return float(str(value).strip())
        except (TypeError, ValueError):
            counts[key] = counts.get(key, 0) + 1
            return None
    if "BLOB" in coltype:
        return value if isinstance(value, (bytes, bytearray, memoryview)) else str(value).encode("utf-8")
    if isinstance(value, (bytes, bytearray)):
        return value                     # a blob in an untyped column stays a blob
    return value if isinstance(value, str) else str(value)


def copy_table(src, dst, table, batch=BATCH_ROWS, placeholder="%s", coerce=True) -> dict:
    """Every row of `table` from `src` (sqlite3) into `dst` (a DB-API
    connection whose placeholder is `placeholder`), in batches, committing
    each. {rows, coerced: {column: n}}."""
    cols = table_columns(src, table)
    names = [c[0] for c in cols]
    part = db_dialect.PARTITIONED.get(table)
    quoted = ", ".join(f'"{n}"' for n in names)
    ins = f'INSERT INTO "{table}" ({quoted}) VALUES ({", ".join([placeholder] * len(names))})'
    counts, n = {}, 0
    cur = src.execute(f'SELECT {quoted} FROM "{table}" ORDER BY rowid') if _has_rowid(src, table) else \
        src.execute(f'SELECT {quoted} FROM "{table}"')
    while True:
        rows = cur.fetchmany(batch)
        if not rows:
            break
        if coerce:
            rows = [tuple(_coerce(v, cols[i][1], part == names[i].lower(), counts, names[i])
                          for i, v in enumerate(r)) for r in rows]
        else:
            rows = [tuple(r) for r in rows]
        dcur = dst.cursor()
        dcur.executemany(ins, rows)
        dst.commit()
        n += len(rows)
    return {"rows": n, "coerced": counts}


def _has_rowid(src, table):
    try:
        src.execute(f'SELECT rowid FROM "{table}" LIMIT 1').fetchone()
        return True
    except sqlite3.OperationalError:
        return False


def reset_sequences(dst, src) -> int:
    """Each copied table's identity / sequence set past its highest id."""
    n = 0
    for name, _sql in sqlite_tables(src):
        cols = table_columns(src, name)
        if not any(c[0] == "id" and c[2] == 1 and "INT" in c[1] for c in cols):
            continue
        cur = dst.cursor()
        cur.execute(f"SELECT setval(pg_get_serial_sequence('{name}', 'id'), "
                    f"COALESCE((SELECT MAX(id) FROM {name}), 0) + 1, false) "
                    f"WHERE pg_get_serial_sequence('{name}', 'id') IS NOT NULL")
        if db_dialect.PARTITIONED.get(name):
            cur.execute(f"SELECT setval('{name}_id_seq', COALESCE((SELECT MAX(id) FROM {name}), 0) + 1, false)")
        n += 1
    dst.commit()
    return n


def table_facts(conn, table, int_pk=True) -> dict:
    """{rows, pk_min, pk_max, pk_sum} of one table, through any DB-API
    connection."""
    cur = conn.cursor()
    cur.execute(f'SELECT COUNT(*) FROM "{table}"')
    out = {"rows": int(cur.fetchone()[0])}
    if int_pk:
        cur.execute(f'SELECT MIN(id), MAX(id), SUM(id) FROM "{table}"')
        r = cur.fetchone()
        out.update(pk_min=r[0], pk_max=r[1], pk_sum=int(r[2]) if r[2] is not None else None)
    return out


def verify(src, dst, tables=None) -> dict:
    """{ok, tables: {name: {source, target, ok}}} — counts, and for an
    integer `id` primary key its min, max and sum, equal on both sides."""
    report, ok = {}, True
    for name, _sql in sqlite_tables(src):
        if tables and name not in tables:
            continue
        cols = table_columns(src, name)
        int_pk = any(c[0] == "id" and c[2] == 1 and "INT" in c[1] for c in cols)
        try:
            a = table_facts(src, name, int_pk)
            b = table_facts(dst, name, int_pk)
            same = a == b
        except Exception as e:
            a, b, same = None, {"error": str(e)[:200]}, False
            try:
                dst.rollback()
            except Exception:
                pass
        report[name] = {"source": a, "target": b, "ok": same}
        ok = ok and same
    return {"ok": ok, "tables": report}


def copy_database(sqlite_path, dst, today=None, build_schema=True, on_table=None) -> dict:
    """The whole SQLite file into the Postgres connection `dst` (psycopg),
    schema first, then every table, the sequences, then verify. Returns the
    report: {schema_statements, tables: {name: {rows, coerced}}, verify}."""
    src = sqlite3.connect(f"file:{sqlite_path}?mode=ro", uri=True)
    try:
        report = {"started": time.time(), "tables": {}}
        plan = schema_plan(src, today=today) if build_schema else {"before": [], "after": []}
        if build_schema:
            cur = dst.cursor()
            for s in plan["before"]:
                for one in db_dialect.split_statements(s):
                    cur.execute(one)
            dst.commit()
            report["schema_statements"] = len(plan["before"])
        for name, _sql in sqlite_tables(src):
            report["tables"][name] = copy_table(src, dst, name)
            if on_table:
                on_table(name, report["tables"][name])
        report["sequences"] = reset_sequences(dst, src)
        # The foreign keys, now that every row is in: one a key refuses is a
        # row SQLite already held that points at nothing — reported, the
        # copy goes on (the report is what the runbook reads).
        report["foreign_keys"] = {"added": 0, "refused": []}
        for stmt in plan["after"]:
            try:
                dst.cursor().execute(stmt)
                dst.commit()
                report["foreign_keys"]["added"] += 1
            except Exception as e:
                dst.rollback()
                report["foreign_keys"]["refused"].append({"statement": stmt, "error": str(e)[:200]})
        report["verify"] = verify(src, dst)
        report["finished"] = time.time()
        return report
    finally:
        src.close()


# ── Postgres -> SQLite (the nightly snapshot on Postgres, the rollback) ─────

def export_to_sqlite(dst_path, url=None, pg=None) -> dict:
    """A consistent snapshot of the Postgres database in a fresh SQLite file
    at `dst_path`, built by the app's own migrations (models.init_db), every
    table both have copied in one REPEATABLE READ transaction, then
    verified (counts). Returns {tables: {name: rows}, verify}."""
    import models
    if os.path.exists(dst_path):
        os.unlink(dst_path)
    models.init_db(dst_path)
    models.ensure_columns(dst_path)
    own = pg is None
    if own:
        import psycopg
        pg = psycopg.connect(url or db_dialect.database_url(), autocommit=False, connect_timeout=10)
    out = sqlite3.connect(dst_path)
    try:
        cur = pg.cursor()
        cur.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ")
        report = {"tables": {}}
        for name, _sql in sqlite_tables(out):
            cols = [c[0] for c in table_columns(out, name)]
            try:
                cur.execute(f'SELECT {", ".join(chr(34) + c + chr(34) for c in cols)} FROM "{name}"')
            except Exception:
                pg.rollback()
                cur = pg.cursor()
                cur.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ")
                report["tables"][name] = {"rows": 0, "missing": True}
                continue
            out.execute(f'DELETE FROM "{name}"')
            n = 0
            while True:
                rows = cur.fetchmany(BATCH_ROWS)
                if not rows:
                    break
                out.executemany(f'INSERT INTO "{name}" ({", ".join(chr(34) + c + chr(34) for c in cols)}) '
                                f'VALUES ({", ".join("?" * len(cols))})', [tuple(r) for r in rows])
                n += len(rows)
            report["tables"][name] = {"rows": n}
        out.commit()
        pg.rollback()
        return report
    finally:
        out.close()
        if own:
            pg.close()


def write_report(report, path) -> str:
    with open(path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, default=str)
    return path
